def pick_language(explicit: str | None, accept_language: str | None, available: list[str]) -> str:
    avail = [lang for lang in (available or ["es"]) if lang in SUPPORTED] or ["es"]
    if explicit and explicit[:2] in avail:
        return explicit[:2]
    for part in (accept_language or "").split(","):
        code = part.split(";")[0].strip()[:2].lower()
        if code in avail:
            return code
    return "es" if "es" in avail else avail[0]
